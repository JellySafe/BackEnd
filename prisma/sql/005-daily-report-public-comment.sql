-- ============================================================================
-- daily_reports.public_comment — 공개용 운영기관 코멘트 (이슈 #56)
--
-- ── 왜 memo 를 그대로 공개하지 않고 컬럼을 새로 두나 ─────────────────────────────
-- daily_reports.memo 는 **운영자가 내부용으로 쓴 값**이다. 지금까지 관리자만 볼 수 있었고,
-- 운영자들은 그 전제로 적어 왔다 — 담당자 이름, 확인 요청, 제보자 관련 메모가 섞여 있을 수
-- 있다. 그 컬럼을 공개 API 에 그대로 붙이면, **쓴 사람이 공개를 전제하지 않고 남긴 글이**
-- 소급해서 전부 공개된다. 되돌릴 수 없고, 무엇이 들어 있는지 미리 다 볼 수도 없다.
--
-- 그래서 공개를 **명시적으로 선택**하게 컬럼을 나눈다. 운영자가 "이건 시민에게 보여도 된다"
-- 고 판단해 적은 값만 공개 경로로 나간다. 기존 memo 는 그대로 내부에 남는다.
--
-- 길이를 300자로 제한한 이유 — 시민 화면의 한 줄 안내다. TEXT 로 두면 화면이 감당 못 할
-- 분량이 들어오고, 결국 어디선가 잘려 문장이 끊긴 채로 나간다.
--
-- 적용: mysql < prisma/sql/005-daily-report-public-comment.sql
--       (DB-first — 운영에서는 prisma migrate 를 쓰지 않는다)
-- ============================================================================

ALTER TABLE daily_reports
  ADD COLUMN public_comment VARCHAR(300) NULL COMMENT '공개용 운영기관 코멘트(시민 화면 노출). 내부 메모(memo)와 분리한다'
  AFTER memo;

/**
 * 정답 한 줄이 **어느 해상도에서 왔는가.**
 *
 * ── 왜 이 구분이 필요한가 ────────────────────────────────────────────────────────────
 * 국립수산과학원 주간보고는 출현을 **시군구 이름**으로 적는다. 위경도가 없다
 * (nifs-report.parser.ts 가 lat/lng 을 항상 null 로 둔다 — PDF 에 좌표가 없기 때문이다).
 *
 * 그래서 "서귀포시에 노무라입깃해파리 저밀도 출현" 한 줄을 정답으로 쓰려면 서귀포시의
 * **모든 해변**에 같은 판정을 붙일 수밖에 없다. 그러면 그 해변들의 정답이 전부 같아져
 * **어느 해변의 예측이 나쁜지 구분할 수 없다.**
 *
 * 그렇다고 버리면 실데이터로는 정확도를 아예 못 잰다 — 실제로 그랬다. 좌표를 요구하는
 * 질의에 NIFS 주간보고를 넣으면 **0건**이 나온다.
 *
 * ── 그래서 버리지 않고 표시한다 ──────────────────────────────────────────────────────
 *   beach  : 그 해변에서 나온 증거(현장 관측 · 쏘임 사고 · 좌표 있는 출현)
 *   region : 시군구 단위 증거(좌표 없는 출현)를 그 구역 해변 전체에 붙인 것
 *
 * 전체 정확도에는 둘 다 센다. **해변별 정확도에는 region 을 넣지 않는다** — 넣으면 같은
 * 시의 해변들이 서로 구별되지 않는 채로 숫자만 그럴듯해진다.
 *
 * ⚠️ 한 (해변, 날짜)에 두 종류가 섞이면 **beach 다.** 현장 관측이 하나라도 있으면 그날 그
 *    해변에 대해 직접 아는 것이 있다는 뜻이고, 시군구 추정이 그것을 덮어서는 안 된다.
 */
export const ACTUAL_GRANULARITIES = ['beach', 'region'] as const;

export type ActualGranularity = (typeof ACTUAL_GRANULARITIES)[number];

/** 해변별 지표에 쓸 수 있는 정답인가. */
export function isBeachLevel(granularity: ActualGranularity): boolean {
  return granularity === 'beach';
}

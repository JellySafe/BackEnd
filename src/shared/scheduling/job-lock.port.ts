/**
 * 배치 중복 실행을 막는 **락**. JobGate 가 이 포트를 통해 문을 잠근다.
 *
 * ── 왜 포트로 뺐나 ──────────────────────────────────────────────────────────────────
 * 게이트의 판정 범위는 **배포 형태에 따라 달라진다.** 한 머신만 돌 때는 프로세스 안의
 * Set 하나로 충분하지만, 머신이 둘이 되는 순간 각 머신이 자기 Set 만 보므로 게이트가
 * 사실상 사라진다 — 크론이 양쪽에서 동시에 돌고, 같은 (beach_id, horizon) 의 is_latest
 * 행을 두 트랜잭션이 갈아치우려 든다.
 *
 * 그 차이는 배치 로직과 무관한 **배포 환경의 문제**이므로, 게이트 본체는 그대로 두고
 * 잠금 수단만 바꿔 끼운다.
 *
 * ── 왜 acquire/release 가 아니라 withLock 인가 ─────────────────────────────────────
 * MySQL 의 `GET_LOCK` 은 **세션(커넥션)에 묶인다.** 잡은 커넥션과 푸는 커넥션이 다르면
 * 풀리지 않는다. acquire/release 를 따로 두면 그 사이에 커넥션 풀이 다른 커넥션을 내줄 수
 * 있어 규약으로 강제할 수 없다. 실행 구간을 통째로 넘겨받으면 구현이 커넥션을 붙잡아 둘 수 있다.
 */
export interface JobLockPort {
  /**
   * `name` 락을 잡고 `fn` 을 실행한다. 이미 다른 실행이 잡고 있으면 **fn 을 실행하지 않고**
   * `{ ran: false }` 를 준다(대기하지 않는다 — 배치는 다음 주기에 다시 온다).
   *
   * `fn` 이 던진 예외는 삼키지 않고 그대로 전파하되, 락은 반드시 푼다.
   */
  withLock<T>(name: string, fn: () => Promise<T>): Promise<{ ran: true; result: T } | { ran: false }>;
}

export const JOB_LOCK = Symbol('JOB_LOCK');
